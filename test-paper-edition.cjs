const assert=require('node:assert/strict');
const E=require('./paper-edition.js');
const books=[{name:'创世记',code:'GEN',first:1,last:2},{name:'歌罗西书',code:'COL',first:3,last:4}];
const data={edition:'rules-1',books,pages:[{b:-1},{b:0,start:'1:1',end:'1:15'},{b:0,start:'1:16',end:'2:8'},{b:1,start:'1:1',end:'1:10'},{b:1,start:'1:11',end:'2:5'}]};
const legacy={books:[{name:'歌罗西书'}],pages:[{}, {b:0,start:'1:15'}]};
assert.equal(E.locate(data,'COL','1:15'),4);
assert.equal(E.locate(data,'歌罗西书','1:1'),3);
assert.equal(E.locate(data,'not-a-book','1:1'),null);
assert.equal(E.locate(data,'GEN','bad-ref'),null);
assert.equal(E.migratePosition({spread:0,zoom:3,focus:'right'},legacy,data).spread,4);
assert.equal(E.migratePosition({spread:0},{books:legacy.books,pages:[{b:0,start:'1:15'},{b:0,start:''}]},data).spread,4,'blank facing page uses the last scripture page');
const raw=new Map([[E.POSITION,JSON.stringify({spread:0})],['paper-bible-ribbon-v1-0',JSON.stringify({version:1,page:9999,bookName:'歌罗西书',ref:'1:15'})]]);
const storage={getItem:k=>raw.get(k)??null,setItem:(k,v)=>raw.set(k,v)};
let scoped=E.storageFor(storage,legacy,data);
assert.equal(JSON.parse(scoped.getItem('paper-bible-ribbon-v1-0')).page,4);
scoped.removeItem('paper-bible-ribbon-v1-0');
scoped=E.storageFor(storage,legacy,data);
assert.equal(scoped.getItem('paper-bible-ribbon-v1-0'),'null');
assert.equal(JSON.parse(storage.getItem('paper-bible-ribbon-v1-0')).page,9999,'legacy bookmark is preserved');
scoped.setItem(E.POSITION,JSON.stringify({spread:2}));
assert.equal(JSON.parse(scoped.getItem(E.POSITION)).spread,2);
assert.equal(JSON.parse(storage.getItem(E.POSITION)).spread,0,'legacy reading position is preserved');
const blocked=E.storageFor({getItem(){throw Error('blocked');}},legacy,data);
assert.equal(blocked.getItem(E.POSITION),null);
console.log('PASS edition isolation, scripture-anchor migration, ribbon removal tombstone, blocked storage');
